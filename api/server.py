def _build_demo_context() -> VFELContext:
    """
    Build a fully-loaded VFELContext from test data.
    Used when running `python api/server.py` directly.
    """
    import sys, os
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

    from data_ingestion.pipeline import IngestionPipeline
    from ledger_core.event_store import EventStore
    from ledger_core.sequence_manager import SequenceManager
    from merkle_forest.forest_manager import ForestManager
    from merkle_forest.tree_snapshot import SnapshotStore
    from block_dag.block_store import BlockStore
    from block_dag.dag_builder import DAGBuilder
    from anchoring.anchor_manager import AnchorManager
    from anchoring.timestamp_anchor import LocalTimestampAnchor
    from anchoring.bitcoin_anchor import BitcoinAnchor
    from anchoring.ethereum_anchor import EthereumAnchor

    data_path = "data/vcp_rta_events.jsonl"
    if not os.path.exists(data_path):
        from data.generate_test_data import generate_chain
        generate_chain(n=500, output_path=data_path)

    seq_mgr   = SequenceManager()
    store     = EventStore(sequence_manager=seq_mgr)
    forest    = ForestManager(snapshot_store=SnapshotStore())
    blk_store = BlockStore()
    builder   = DAGBuilder(store, forest, blk_store, events_per_block=100)
    builder.initialize_genesis()

    pipeline = IngestionPipeline(file_paths=data_path, num_shards=8)
    for se in pipeline.run():
        ar = store.append(se.event)
        if ar.success:
            forest.append(ar.stored_event.shard_key, ar.stored_event.stored_event_hash)
            builder.feed(ar.stored_event)
    builder.flush()

    anchor_mgr = AnchorManager()
    anchor_mgr.register_backend(LocalTimestampAnchor(node_id="demo-node"))
    anchor_mgr.register_backend(BitcoinAnchor(mode="simulation"))
    anchor_mgr.register_backend(EthereumAnchor(mode="simulation"))
    anchor_mgr.anchor(forest.forest_root(), metadata={"source": "startup"})

    logger.info(
        "Demo context loaded: %d events, %d blocks",
        store.total_events(),
        len(blk_store.all_blocks()),
    )
    return VFELContext(
        event_store=store,
        forest_manager=forest,
        block_store=blk_store,
        dag_builder=builder,
        anchor_manager=anchor_mgr,
    )


# Importable ASGI app — `uvicorn api.server:app`
try:
    _ctx = _build_demo_context()
    app = create_app(_ctx)
except Exception as _e:
    logger.warning("Could not build demo context: %s", _e)
    app = None